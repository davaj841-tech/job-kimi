export function resumeThemeById(id) {
  let n = Number(id) || 1
  if (n < 1) n = 1
  if (n > 15) n = ((n - 1) % 15) + 1
  return RESUME_THEMES.find((t) => t.id === n) || RESUME_THEMES[0]
}
